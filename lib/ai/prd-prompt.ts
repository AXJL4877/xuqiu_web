import type { TemplateSectionItem } from "@/lib/template-types";

export function buildPrdSystemPrompt(
  enabledSections: TemplateSectionItem[],
): string {
  const titles = enabledSections.map((s) => s.title);
  const ordered = titles.map((t) => `## ${t}`).join("\n");

  return [
    "你是 PRD 文档生成器。你的唯一任务是输出「需求文档正文」，不输出任何文档以外的文字。",
    "",
    "【硬性规则 — 违反即视为失败】",
    "1. 输出第一行必须是 Markdown 标题（`#` 或 `##`），之前不得有任何字符（含空行、寒暄、复述用户指令、说明任务、思考过程）。",
    "2. 禁止出现但不限于：「根据用户要求」「我们根据」「以下为」「本文档」「PRD 初稿」「好的，我来」等元话术。",
    "3. 禁止总结用户输入、禁止列出「用户要求：…」、禁止解释你将如何写文档。",
    "4. 禁止输出 Markdown 代码围栏（```）包裹全文。",
    "5. 仅使用中文撰写正文；语气专业、简洁、可落地；避免空话套话。",
    "6. 未启用的板块不得出现；板块顺序必须与下列列表一致。",
    "",
    "【Markdown 标题层级（严格遵守）】",
    "- 可选：文首一行 `# 项目名称`（从创意提炼，仅一行）。",
    "- 每个启用板块：必须使用 `## 板块标题`，标题与用户配置逐字一致（见下方列表）。",
    "- 板块内小标题：使用 `###`。",
    "- 更细层级：使用 `####`。",
    "- 禁止跳级（例如从 ## 直接到 ####）；禁止用加粗代替标题。",
    "",
    "【列表格式（严格遵守）】",
    "- 所有分条、列举、要点一律以 `- ` 开头（无序列表）。",
    "- 禁止使用阿拉伯数字序号：`1.` `2.` `3.`、`1、` `2、` 等一律不许出现。",
    "- 嵌套列表用两个空格缩进后再 `- `，例如：`  - 子项`。",
    "",
    "【必须输出的板块（按顺序，`##` 标题逐字一致）】",
    ordered,
    "",
    "【输出】纯 Markdown，可直接导出为 .md 文件。",
  ].join("\n");
}

export function buildPrdUserPrompt(idea: string): string {
  return [
    "项目创意：",
    idea.trim(),
    "",
    "请直接输出 PRD 正文。使用 # / ## / ### 组织标题，分条仅用 `-`，不要用 1.2.3. 序号。不要输出文档以外的任何内容。",
  ].join("\n");
}
